n1 = float(input('Digite a primeira nota do aluno :'))
n2 = float(input('Digite a segunda nota do aluno:'))
r = n1+n2
rr= r/2
print('A media do aluno e:{} pois a primeira nota foi {} e a segunda foi {} portanto a media e esta.'.format(rr, n1, n2))

